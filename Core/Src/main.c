static const char *last_btn_str = "None       ";
static uint8_t lcd_dirty = 1;

static void update_lcd_status(void) {
  char line_buf[17];

  snprintf(line_buf, sizeof(line_buf), "TL1:%-3s  TL2:%-3s",
           traffic_color_str(traffic_get(TRAFFIC_ROAD_1)),
           traffic_color_str(traffic_get(TRAFFIC_ROAD_2)));
  LCD_SetCursor(0, 0);
  LCD_SendString(line_buf);

  snprintf(line_buf, sizeof(line_buf), "Btn: %-11s", last_btn_str);
  LCD_SetCursor(0, 1);
  LCD_SendString(line_buf);
}

/**
 * @brief Step 5 Demo Task: tests debounced button presses, 1s long-press,
 *        and traffic_light module under the O(1) scheduler.
 */
static void test_button_traffic_task(void) {
  if (isButtonPressed(BTN_1)) {
    /* Button 1 (BU1_A / PA8): Road 1 = RED, Road 2 = GREEN */
    traffic_set_both(LIGHT_RED, LIGHT_GREEN);
    last_btn_str = "BU1_A (D7) ";
    lcd_dirty = 1;
  } else if (isButtonPressed(BTN_2)) {
    /* Button 2 (BU1_B / PA9): Road 1 = RED, Road 2 = AMBER */
    traffic_set_both(LIGHT_RED, LIGHT_AMBER);
    last_btn_str = "BU1_B (D8) ";
    lcd_dirty = 1;
  } else if (isButtonPressed(BTN_3)) {
    /* Button 3 (BU2_A / PC7): Road 1 = GREEN, Road 2 = RED */
    traffic_set_both(LIGHT_GREEN, LIGHT_RED);
    last_btn_str = "BU2_A (D9) ";
    lcd_dirty = 1;
  } else if (isButtonPressed(BTN_4)) {
    /* Button 4 (BU2_B / PB6): Road 1 = AMBER, Road 2 = RED */
    traffic_set_both(LIGHT_AMBER, LIGHT_RED);
    last_btn_str = "BU2_B (D10)";
    lcd_dirty = 1;
  }

  /* Long-press (>= 1 s) on Button 4 turns both lights OFF */
  if (isButtonPressed1s(BTN_4)) {
    traffic_off_all();
    last_btn_str = "BU2_B HOLD ";
    lcd_dirty = 1;
  }

  /* Mirror any held button onto on-board LED LD2 (PA5) */
  uint8_t any_held = isButtonHeld(BTN_1) || isButtonHeld(BTN_2) ||
                     isButtonHeld(BTN_3) || isButtonHeld(BTN_4);
  HAL_GPIO_WritePin(LD2_GPIO_Port, LD2_Pin,
                    any_held ? GPIO_PIN_SET : GPIO_PIN_RESET);

  if (lcd_dirty) {
    update_lcd_status();
    lcd_dirty = 0;
  }
}
